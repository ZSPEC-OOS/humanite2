import type { Domain } from '../types'

export interface ReferencePassage {
  domain: Domain
  text: string
  // Provenance is mandatory for any real entry: a named human author,
  // publication, or internal contributor. Never 'placeholder' for a
  // passage actually used in calibration or style-target derivation.
  source: string
}

// Minimum passages required per domain before this set is trusted to
// calibrate a detector's fixed-false-positive-rate threshold (see
// calibrateDetector in runBenchmark.ts) or to derive Phase 3 style targets.
// Below this count, both consumers report null rather than a number
// computed from too little — or entirely placeholder — data.
export const MIN_REFERENCE_PASSAGES_PER_DOMAIN = 10

// NOT YET POPULATED — this is a known, intentional gap, not an oversight.
//
// The plan calls for "10 human-written passages per domain, used to derive
// style targets" (Phase 2), and this repository's own benchmark runner
// additionally needs genuinely human-written text to calibrate each
// detector's decision threshold at a fixed false-positive rate (the
// "detector rate at a fixed false-positive rate" metric Phase 2 tracks).
//
// I (the model implementing this phase) cannot populate this myself:
// anything I write is AI-generated by construction, so using it here would
// silently corrupt both downstream uses — Phase 3 would derive "human"
// style targets from Claude's own prose, and the detector calibration would
// tune a "human-written" threshold against machine-generated text. That is
// exactly the class of unlabeled fabricated precision the plan's own
// governing principles rule out ("Measure before optimizing", "Expose only
// what can be measured").
//
// This needs a human curator (or a corpus with clear, checked provenance)
// to populate, at MIN_REFERENCE_PASSAGES_PER_DOMAIN passages per domain,
// each carrying real `source` attribution. Until then, hasSufficientReferenceData
// correctly reports false for every domain, and callers (runBenchmark.ts,
// and Phase 3 when it lands) must treat that as "not available" rather than
// falling back to a default.
export const REFERENCE_PASSAGES: ReferencePassage[] = []

export function referencePassagesByDomain(domain: Domain): ReferencePassage[] {
  return REFERENCE_PASSAGES.filter(p => p.domain === domain)
}

export function hasSufficientReferenceData(domain: Domain): boolean {
  return referencePassagesByDomain(domain).length >= MIN_REFERENCE_PASSAGES_PER_DOMAIN
}
